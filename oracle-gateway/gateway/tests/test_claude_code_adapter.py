"""Claude Code adapter: native JSONL to canonical (PLAN 7.1)."""

from conftest import fixture_lines

from oracle_gateway.adapters import get_adapter

LINES = fixture_lines("claude_code_sample.jsonl")


def parse():
    return get_adapter("claude_code").parse(LINES)


def by_id(batch, external_id):
    return next(e for e in batch.events if e.external_id == external_id)


def test_ingests_only_conversation_lines_and_counts_the_rest_as_skipped():
    batch = parse()
    # 4 chrome + ai-title + attachment + malformed = 7 skipped;
    # 3 user + 3 assistant + 1 tool_result + 1 summary = 8 conversation events
    assert len(batch.events) == 8
    assert batch.skipped == 7


def test_session_header_comes_from_the_conversation_lines():
    session = parse().session
    assert session.external_id == "11111111-2222-3333-4444-555555555555"
    assert session.agent_kind == "claude_code"
    assert session.workspace == "/Users/demo/dev/payments"
    assert session.branch == "feature/refunds"
    assert session.agent_version == "2.1.258"
    assert session.metadata["entrypoint"] == "cli"


def test_started_at_is_the_earliest_event_timestamp():
    assert parse().session.started_at.isoformat() == "2026-09-12T16:54:26.898000+00:00"


def test_title_prefers_the_title_claude_code_generated_itself():
    assert parse().session.title == "Refund endpoint for payments service"


def test_title_falls_back_to_the_first_real_prompt_when_there_is_no_ai_title():
    without = [line for line in LINES if '"ai-title"' not in line]
    batch = get_adapter("claude_code").parse(without)
    assert batch.session.title == "Add a refund endpoint to the payments service"


def test_slash_command_echoes_never_become_the_title_even_unflagged():
    """Claude Code does not set isMeta on the <command-name> line itself."""
    without = [line for line in LINES if '"ai-title"' not in line]
    batch = get_adapter("claude_code").parse(without)
    assert "command-name" not in (batch.session.title or "")


def test_command_echo_lines_are_still_stored_as_events():
    assert by_id(parse(), "aaaa0000-0000-0000-0000-00000000000a").type == "user_message"


def test_string_content_becomes_a_single_text_block():
    event = by_id(parse(), "aaaa0000-0000-0000-0000-000000000002")
    assert event.type == "user_message"
    assert event.role == "user"
    assert event.content == [{"type": "text", "text": "Add a refund endpoint to the payments service"}]
    assert event.parent_external_id == "aaaa0000-0000-0000-0000-000000000001"


def test_meta_lines_are_ingested_and_flagged_not_dropped():
    event = by_id(parse(), "aaaa0000-0000-0000-0000-000000000001")
    assert event.metadata["is_meta"] is True


def test_thinking_only_assistant_line_is_typed_thinking():
    event = by_id(parse(), "aaaa0000-0000-0000-0000-000000000003")
    assert event.type == "thinking"
    assert event.role == "assistant"
    assert event.model == "claude-opus-5"
    assert event.usage["cache_read_input_tokens"] == 27948
    assert event.metadata["request_id"] == "req_demo_1"


def test_text_assistant_line_is_typed_assistant_message():
    assert by_id(parse(), "aaaa0000-0000-0000-0000-000000000004").type == "assistant_message"


def test_tool_use_line_is_typed_tool_call_and_keeps_the_block():
    event = by_id(parse(), "aaaa0000-0000-0000-0000-000000000005")
    assert event.type == "tool_call"
    assert event.content[0]["name"] == "Bash"
    assert event.content[0]["input"]["command"] == "ls src/api"
    assert "Bash(" in event.text


def test_tool_result_line_is_typed_tool_result():
    event = by_id(parse(), "aaaa0000-0000-0000-0000-000000000006")
    assert event.type == "tool_result"
    assert event.content[0]["tool_use_id"] == "toolu_demo_1"
    assert "charges.py" in event.text


def test_summary_line_gets_a_stable_derived_id_and_a_timestamp():
    event = by_id(parse(), "summary:aaaa0000-0000-0000-0000-000000000006")
    assert event.type == "summary"
    assert event.content == [{"type": "text", "text": "Add refund endpoint mirroring charges"}]
    assert event.occurred_at is not None


def test_every_event_keeps_its_raw_line():
    assert all(event.raw for event in parse().events)


def test_parsing_is_deterministic_so_re_shipping_dedupes():
    assert [e.external_id for e in parse().events] == [e.external_id for e in parse().events]


def test_a_long_command_caveat_is_still_recognised_after_truncation():
    """The chrome check must run on the full text, not the 120-char title slice."""
    long_caveat = (
        '{"parentUuid":null,"type":"user","message":{"role":"user","content":'
        '"<local-command-caveat>Caveat: The messages below were generated by the user '
        'while running local commands. DO NOT respond to these messages or otherwise '
        'consider them in your response unless the user explicitly asks you to.'
        '</local-command-caveat>"},"uuid":"aaaa0000-0000-0000-0000-00000000000b",'
        '"timestamp":"2026-09-12T16:54:25.000Z","cwd":"/Users/demo/dev/payments",'
        '"sessionId":"11111111-2222-3333-4444-555555555555"}'
    )
    without_ai_title = [line for line in LINES if '"ai-title"' not in line]
    batch = get_adapter("claude_code").parse([long_caveat] + without_ai_title)
    assert batch.session.title == "Add a refund endpoint to the payments service"
